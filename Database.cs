    private static readonly string EnsureBlockMutationEnvelopeLengthConstraint = $@"DO $migration$
    BEGIN
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns column_row
            WHERE column_row.table_schema = current_schema()
              AND column_row.table_name = 'blockmutationlogs'
              AND column_row.column_name = 'envelope_data'
              AND column_row.data_type = 'bytea'
        ) AND NOT EXISTS (
            SELECT 1
            FROM pg_catalog.pg_constraint constraint_row
            JOIN pg_catalog.pg_class table_row ON table_row.oid = constraint_row.conrelid
            JOIN pg_catalog.pg_namespace schema_row ON schema_row.oid = table_row.relnamespace
            WHERE schema_row.nspname = current_schema()
              AND table_row.relname = 'blockmutationlogs'
              AND constraint_row.conname = 'ck_blockmutationlogs_envelope_data_length'
        ) THEN
            ALTER TABLE blockmutationlogs
                ADD CONSTRAINT ck_blockmutationlogs_envelope_data_length
                CHECK (octet_length(envelope_data) <= {BlockStateEnvelope.MaximumEncodedBytes});
        END IF;
    END
    $migration$;";

