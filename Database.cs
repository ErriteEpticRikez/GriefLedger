    public void Dispose() {
        lock (lifecycleLock) {
            if (disposed) return;
            acceptingWrites = false;
            acceptingReads = false;
            databaseTasks.CompleteAdding();
            disposed = true;
        }

        workerThread.Join();
        readsDrained.Wait();
        databaseTasks.Dispose();
        readsDrained.Dispose();
        dataSource.Dispose();
    }
