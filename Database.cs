    public (byte[]? data, int encoding) CompressText(string? value) {
        if (value == null) return (null, 0);

        byte[] utf8Bytes = System.Text.Encoding.UTF8.GetBytes(value);
        using var outputStream = new MemoryStream();
        using (var brotliStream = new System.IO.Compression.BrotliStream(outputStream, System.IO.Compression.CompressionLevel.Optimal)) {
            brotliStream.Write(utf8Bytes, 0, utf8Bytes.Length);
        }

        byte[] compressedBytes = outputStream.ToArray();
        if (compressedBytes.Length < utf8Bytes.Length) {
            return (compressedBytes, 2);
        }
        return (utf8Bytes, 1);
    }

    public string? DecompressText(byte[]? data, int encoding) {
        if (data == null || encoding == 0) return null;
        if (encoding == 1) return System.Text.Encoding.UTF8.GetString(data);
        if (encoding == 2) {
            using var inputStream = new MemoryStream(data);
            using var brotliStream = new System.IO.Compression.BrotliStream(inputStream, System.IO.Compression.CompressionMode.Decompress);
            using var outputStream = new MemoryStream();
            brotliStream.CopyTo(outputStream);
            return System.Text.Encoding.UTF8.GetString(outputStream.ToArray());
        }
        return null;
    }

    private long GetOrInsertPlayer(NpgsqlConnection connection, string? playername, string? playeruid, NpgsqlTransaction? transaction = null) {
        if (playername == null && playeruid == null) return -1;

        using var cmd = connection.CreateCommand();
        cmd.Transaction = transaction;
        if (playeruid != null) {
            cmd.CommandText = @"INSERT INTO players (playeruid, last_playername)
                VALUES (@uid, @name)
                ON CONFLICT (playeruid) DO UPDATE
                SET last_playername = EXCLUDED.last_playername
                RETURNING id;";
            AddParameter(cmd, "@uid", NpgsqlDbType.Text, playeruid);
            AddParameter(cmd, "@name", NpgsqlDbType.Text, playername);
            return Convert.ToInt64(cmd.ExecuteScalar());
        }
        else {
            cmd.CommandText = "INSERT INTO players (last_playername) VALUES (@name) RETURNING id;";
            AddParameter(cmd, "@name", NpgsqlDbType.Text, playername);
            return Convert.ToInt64(cmd.ExecuteScalar());
        }
    }

    /// <summary>Queues an immutable append on the same FIFO writer used by the legacy logs.</summary>
    public Task<long> EnqueueBlockMutationAppend(BlockMutationAppend append) {
        ArgumentNullException.ThrowIfNull(append);
        byte[] envelope = append.CopyEnvelopeData();
        return QueueResultWrite((connection, setResult) => {
            using NpgsqlTransaction transaction = connection.BeginTransaction();
            if (append.EntryKind == BlockMutationEntryKind.Rollback) {
                using var sourceCmd = connection.CreateCommand();
                sourceCmd.Transaction = transaction;
                sourceCmd.CommandText = @"SELECT entry_kind, action_kind, dimension, x, y, z,
                        envelope_data, envelope_encoding
                    FROM blockmutationlogs
                    WHERE id = @source_mutation_id
                    FOR SHARE;";
                AddParameter(sourceCmd, "@source_mutation_id", NpgsqlDbType.Bigint, append.SourceMutationId);
                using (var sourceReader = sourceCmd.ExecuteReader()) {
                    if (!sourceReader.Read()) throw new InvalidOperationException("The rollback source mutation does not exist or is not committed.");
                    if (sourceReader.GetInt32(0) != (int)BlockMutationEntryKind.Mutation) {
                        throw new InvalidOperationException("A rollback source must be a mutation entry.");
                    }
                    BlockMutationActionKind sourceAction = (BlockMutationActionKind)sourceReader.GetInt32(1);
                    if (!Enum.IsDefined(sourceAction) || sourceAction is BlockMutationActionKind.Unknown or BlockMutationActionKind.Rollback) {
                        throw new InvalidOperationException("A rollback source must use a supported mutation action.");
                    }
                    if (sourceReader.GetInt32(2) != append.Dimension || sourceReader.GetInt32(3) != append.X
                        || sourceReader.GetInt32(4) != append.Y || sourceReader.GetInt32(5) != append.Z) {
                        throw new InvalidOperationException("A rollback entry must use the source mutation's dimension and absolute coordinates.");
                    }
                    int sourceEncoding = sourceReader.GetInt32(7);
                    if (sourceEncoding != BlockStateEnvelope.BinaryEncoding) {
                        throw new InvalidOperationException("The rollback source uses an unsupported envelope encoding.");
                    }
                    BlockStateEnvelope sourceEnvelope = BlockStateEnvelope.Decode(sourceReader.GetFieldValue<byte[]>(6));
                    var exactInverse = new BlockStateEnvelope(sourceEnvelope.After, sourceEnvelope.Before);
                    byte[] expectedInverseBytes = exactInverse.Encode();
                    if (!append.DecodeEnvelope().Equals(exactInverse)
                        || !envelope.AsSpan().SequenceEqual(expectedInverseBytes)) {
                        throw new InvalidOperationException("A rollback entry must store the exact inverse of its source mutation envelope.");
                    }
                }
            }
            long actorPlayerId = GetOrInsertPlayer(connection, append.ActorPlayerName, append.ActorPlayerUid, transaction);
            long operatorPlayerId = GetOrInsertPlayer(connection, append.OperatorPlayerName, append.OperatorPlayerUid, transaction);
            using var cmd = connection.CreateCommand();
            cmd.Transaction = transaction;
            cmd.CommandText = @"INSERT INTO blockmutationlogs
                (timestamp_utc, player_id, entry_kind, action_kind, dimension, x, y, z,
                 envelope_data, envelope_encoding, source_mutation_id, rollback_outcome,
                 failure_code, operator_player_id)
                VALUES
                (@timestamp_utc, @player_id, @entry_kind, @action_kind, @dimension, @x, @y, @z,
                 @envelope_data, @envelope_encoding, @source_mutation_id, @rollback_outcome,
                 @failure_code, @operator_player_id)
                RETURNING id;";
            AddParameter(cmd, "@timestamp_utc", NpgsqlDbType.Bigint, append.TimestampUtc);
            AddParameter(cmd, "@player_id", NpgsqlDbType.Bigint, actorPlayerId == -1 ? null : actorPlayerId);
            AddParameter(cmd, "@entry_kind", NpgsqlDbType.Integer, (int)append.EntryKind);
            AddParameter(cmd, "@action_kind", NpgsqlDbType.Integer, (int)append.ActionKind);
            AddParameter(cmd, "@dimension", NpgsqlDbType.Integer, append.Dimension);
            AddParameter(cmd, "@x", NpgsqlDbType.Integer, append.X);
            AddParameter(cmd, "@y", NpgsqlDbType.Integer, append.Y);
            AddParameter(cmd, "@z", NpgsqlDbType.Integer, append.Z);
            AddParameter(cmd, "@envelope_data", NpgsqlDbType.Bytea, envelope);
            AddParameter(cmd, "@envelope_encoding", NpgsqlDbType.Integer, append.EnvelopeEncoding);
            AddParameter(cmd, "@source_mutation_id", NpgsqlDbType.Bigint, append.SourceMutationId);
            AddParameter(cmd, "@rollback_outcome", NpgsqlDbType.Integer, append.RollbackOutcome.HasValue ? (int)append.RollbackOutcome.Value : null);
            AddParameter(cmd, "@failure_code", NpgsqlDbType.Text, append.FailureCode);
            AddParameter(cmd, "@operator_player_id", NpgsqlDbType.Bigint, operatorPlayerId == -1 ? null : operatorPlayerId);
            long id = Convert.ToInt64(cmd.ExecuteScalar());
            transaction.Commit();
            setResult(id);
        }, false);
    }

    public Task<long> EnqueueBlockMutationAppendAsync(BlockMutationAppend append) => EnqueueBlockMutationAppend(append);

    /// <summary>
    /// Enqueues a FIFO barrier and returns the durable maximum ledger id after every earlier
    /// queued write has completed. Any earlier writer failure is surfaced instead of returning
    /// a potentially misleading cutoff.
    /// </summary>
    public Task<long> GetDurableBlockMutationCutoffAsync() {
        return QueueResultWrite((connection, setResult) => {
            using NpgsqlTransaction transaction = connection.BeginTransaction();
            using var cmd = connection.CreateCommand();
            cmd.Transaction = transaction;
            // SHARE conflicts with the ROW EXCLUSIVE lock used by INSERT/UPDATE/DELETE. This
            // waits for existing direct writers and excludes new ones until MAX(id) is read and
            // committed, making the result a stable durable prefix for normal identity inserts.
            cmd.CommandText = @"LOCK TABLE blockmutationlogs IN SHARE MODE;
                SELECT COALESCE(MAX(id), 0) FROM blockmutationlogs;";
            long cutoff = Convert.ToInt64(cmd.ExecuteScalar());
            transaction.Commit();
            setResult(cutoff);
        }, true);
    }

    public Task<long> GetDurableMutationCutoffAsync() => GetDurableBlockMutationCutoffAsync();

    /// <summary>Resolves an immutable UID exactly. World/player APIs are never touched by this read.</summary>
    public Task<BlockMutationPlayer?> ResolveBlockMutationPlayerByUidAsync(string playerUid,
        CancellationToken cancellationToken = default) {
        if (string.IsNullOrWhiteSpace(playerUid)) throw new ArgumentException("A nonempty immutable player UID is required.", nameof(playerUid));
        return QueueReadAsync("resolve exact-ledger player UID", async (connection, token) => {
            await using NpgsqlCommand cmd = connection.CreateCommand();
            cmd.CommandText = @"SELECT id, playeruid, last_playername
                FROM players
                WHERE playeruid = @player_uid
                ORDER BY id
                LIMIT 2;";
            AddParameter(cmd, "@player_uid", NpgsqlDbType.Text, playerUid);
            await using NpgsqlDataReader reader = await cmd.ExecuteReaderAsync(token).ConfigureAwait(false);
            BlockMutationPlayer? player = null;
            if (await reader.ReadAsync(token).ConfigureAwait(false)) {
                player = ReadPlayer(reader);
            }
            if (await reader.ReadAsync(token).ConfigureAwait(false)) {
                throw new InvalidOperationException("The immutable player UID is not unique in the players table.");
            }
            return player;
        }, cancellationToken);
    }

    /// <summary>Resolves a case-insensitive last-known name only when it identifies one player row.</summary>
    public Task<BlockMutationPlayerNameResolution> ResolveBlockMutationPlayerByNameAsync(string playerName,
        CancellationToken cancellationToken = default) {
        if (string.IsNullOrWhiteSpace(playerName)) throw new ArgumentException("A nonempty player name is required.", nameof(playerName));
        return QueueReadAsync("resolve exact-ledger player name", async (connection, token) => {
            await using NpgsqlCommand cmd = connection.CreateCommand();
            cmd.CommandText = @"SELECT id, playeruid, last_playername
                FROM players
                WHERE lower(last_playername) = lower(@player_name)
                ORDER BY id
                LIMIT 2;";
            AddParameter(cmd, "@player_name", NpgsqlDbType.Text, playerName);
            var players = new List<BlockMutationPlayer>();
            await using NpgsqlDataReader reader = await cmd.ExecuteReaderAsync(token).ConfigureAwait(false);
            while (await reader.ReadAsync(token).ConfigureAwait(false)) players.Add(ReadPlayer(reader));
            return new BlockMutationPlayerNameResolution(players.AsReadOnly());
        }, cancellationToken);
    }

