                }
            }

            Main.API.Event.EnqueueMainThreadTask(() => {
                foreach (var log in logs) {
                    Main.API.SendMessage(player, GlobalConstants.InfoLogChatGroup, log, EnumChatType.CommandSuccess);
                }
            }, "SendEntityLogWithEntityID");
        });
    }

    public (int, int, int)? GetLastEntityCoordsLog(string entityID) {
        const string operation = "get last entity coordinates";
        if (!TryBeginRead(operation)) return null;

        try {
            using var connection = dataSource.OpenConnection();

            using var cmd = connection.CreateCommand();
            cmd.CommandText = LastEntityCoordsQuery;

            AddParameter(cmd, "@entityid", NpgsqlDbType.Text, entityID);

            using var reader = cmd.ExecuteReader();
            if (reader.Read()) {
                int x = reader.GetInt32(0);
                int y = reader.GetInt32(1);
                int z = reader.GetInt32(2);

                return (x, y, z);
            }
            return null;
        }
        catch (Exception ex) {
            LogError("GriefLedger: Database read '" + operation + "' failed: " + ex);
            throw;
        }
        finally {
            EndRead();
        }
    }

    public void AddContainerLog(string? playername, string? playeruid, string actiontype, string containerid, string? itemstack, int quantity) {
        long timestamp = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        QueueWrite((connection) => {
            long playerId = GetOrInsertPlayer(connection, playername, playeruid);
            var compressed = CompressText(itemstack);

            using var cmd = connection.CreateCommand();
            cmd.CommandText = @"INSERT INTO containerlogs (timestamp_utc, player_id, containerid, itemstack_data, itemstack_encoding, quantity, actiontype)
            VALUES (@timestamp, @player_id, @containerid, @itemstack_data, @itemstack_encoding, @quantity, @actiontype)";

            AddParameter(cmd, "@timestamp", NpgsqlDbType.Bigint, timestamp);
            AddParameter(cmd, "@player_id", NpgsqlDbType.Bigint, playerId == -1 ? null : playerId);
            AddParameter(cmd, "@actiontype", NpgsqlDbType.Integer, ActionTypeMap.TryGetValue(actiontype, out int val) ? val : 5);
            AddParameter(cmd, "@containerid", NpgsqlDbType.Text, containerid);
            AddParameter(cmd, "@itemstack_data", NpgsqlDbType.Bytea, compressed.data);
            AddParameter(cmd, "@itemstack_encoding", NpgsqlDbType.Integer, compressed.encoding);
            AddParameter(cmd, "@quantity", NpgsqlDbType.Integer, quantity);

            cmd.ExecuteNonQuery();
        });
    }

