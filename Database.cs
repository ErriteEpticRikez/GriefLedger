public sealed class DatabaseWriterQueueFullException : InvalidOperationException {
    public DatabaseWriterQueueFullException(int capacity)
        : base($"The database writer queue reached its bounded capacity of {capacity} work items.") {
        Capacity = capacity;
    }
    public int Capacity { get; }
}

public sealed class DatabaseWriterUnavailableException : InvalidOperationException {
    public DatabaseWriterUnavailableException(Exception terminalFailure)
        : base("The database writer previously failed and is unavailable for this database lifetime.",
            terminalFailure ?? throw new ArgumentNullException(nameof(terminalFailure))) { }
}

