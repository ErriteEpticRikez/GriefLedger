    public Database() : this(DefaultWriterQueueCapacity) { }

    internal Database(int writerQueueCapacity) {
        if (writerQueueCapacity <= 0) throw new ArgumentOutOfRangeException(nameof(writerQueueCapacity));
        dataSource = DatabaseConfiguration.CreateDataSource();
        try {
            using (var connection = dataSource.OpenConnection()) {
                using (var versionCmd = connection.CreateCommand()) {
                    versionCmd.CommandText = "SHOW server_version_num;";
                    if (Convert.ToInt32(versionCmd.ExecuteScalar()) < 170000) {
                        throw new InvalidOperationException("GriefLedger requires PostgreSQL 17 or newer.");
                    }
                }

                using var transaction = connection.BeginTransaction();
                using (var cmd = connection.CreateCommand()) {
                    cmd.Transaction = transaction;
                    cmd.CommandText = CreatePlayersTable;
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = CreateBlockLogsTable;
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = CreateEntityLogsTable;
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = CreateContainerLogsTable;
                    cmd.ExecuteNonQuery();
                    // Additive migration for installations bootstrapped with the original four tables.
                    cmd.CommandText = CreateBlockMutationLogsTable;
                    cmd.ExecuteNonQuery();
                    // Existing exact-ledger schemas predate the per-row envelope bound. Add it
                    // before shape validation; an incompatible same-name constraint is preserved
                    // here and then rejected by the canonical validator below.
                    cmd.CommandText = EnsureBlockMutationEnvelopeLengthConstraint;
                    cmd.ExecuteNonQuery();

                    ValidateSchema(connection, transaction);

                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blocklogs_coords ON blocklogs(x, y, z);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_entitylogs_coords ON entitylogs(x, y, z);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_containerlogs_id ON containerlogs(containerid);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_entitylogs_entityid_id_desc ON entitylogs(entityid, id DESC);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_containerlogs_containerid_id_desc ON containerlogs(containerid, id DESC);";
                    cmd.ExecuteNonQuery();

                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blocklogs_ts ON blocklogs(timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blocklogs_pid_ts ON blocklogs(player_id, timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blocklogs_act_ts ON blocklogs(actiontype, timestamp_utc);";
                    cmd.ExecuteNonQuery();

                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_entitylogs_ts ON entitylogs(timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_entitylogs_pid_ts ON entitylogs(player_id, timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_entitylogs_act_ts ON entitylogs(actiontype, timestamp_utc);";
                    cmd.ExecuteNonQuery();

                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_containerlogs_ts ON containerlogs(timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_containerlogs_pid_ts ON containerlogs(player_id, timestamp_utc);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_containerlogs_act_ts ON containerlogs(actiontype, timestamp_utc);";
                    cmd.ExecuteNonQuery();

                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blockmutationlogs_player_dimension_id_desc ON blockmutationlogs(player_id, dimension, id DESC);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blockmutationlogs_replay_candidates ON blockmutationlogs(player_id, dimension, action_kind, x, y, z, id DESC) WHERE entry_kind = 0;";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blockmutationlogs_dimension_coords_id_desc ON blockmutationlogs(dimension, x, y, z, id DESC);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE INDEX IF NOT EXISTS idx_blockmutationlogs_source_outcome ON blockmutationlogs(source_mutation_id, rollback_outcome);";
                    cmd.ExecuteNonQuery();
                    cmd.CommandText = "CREATE UNIQUE INDEX IF NOT EXISTS ux_blockmutationlogs_successful_source ON blockmutationlogs(source_mutation_id) WHERE entry_kind = 1 AND rollback_outcome = 1;";
                    cmd.ExecuteNonQuery();

                    ValidateBlockMutationIndexes(connection, transaction);
                }
                transaction.Commit();
            }
        }
        catch {
            dataSource.Dispose();
            throw;
        }

        databaseTasks = new BlockingCollection<WriterWorkItem>(new ConcurrentQueue<WriterWorkItem>(), writerQueueCapacity);
        workerThread = new Thread(WorkerLoop);
        workerThread.IsBackground = true;
        workerThread.Name = "GriefLedger database writer";
        workerThread.Start();
    }

    private static void ValidateSchema(NpgsqlConnection connection, NpgsqlTransaction transaction) {
        var actualColumns = new Dictionary<string, Dictionary<string, (string Type, bool IsIdentity, bool IsNullable)>>(StringComparer.Ordinal);
        using var cmd = connection.CreateCommand();
        cmd.Transaction = transaction;
        cmd.CommandText = @"SELECT table_name, column_name, data_type, is_identity, is_nullable
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = ANY(@tables);";
        AddParameter(cmd, "@tables", NpgsqlDbType.Array | NpgsqlDbType.Text, new List<string>(RequiredColumnTypes.Keys).ToArray());
        using (var reader = cmd.ExecuteReader()) {
            while (reader.Read()) {
                string table = reader.GetString(0);
                if (!actualColumns.TryGetValue(table, out var columns)) {
                    columns = new Dictionary<string, (string Type, bool IsIdentity, bool IsNullable)>(StringComparer.Ordinal);
                    actualColumns[table] = columns;
                }
                columns[reader.GetString(1)] = (reader.GetString(2), reader.GetString(3) == "YES", reader.GetString(4) == "YES");
            }
        }

        foreach (var table in RequiredColumnTypes) {
            if (!actualColumns.TryGetValue(table.Key, out var columns)) {
                throw new InvalidOperationException("GriefLedger database schema validation failed: required table " + table.Key + " was not found in the current schema.");
            }
            foreach (var expectedColumn in table.Value) {
                if (!columns.TryGetValue(expectedColumn.Key, out var actual)) {
                    throw new InvalidOperationException("GriefLedger database schema validation failed: required column " + table.Key + "." + expectedColumn.Key + " was not found.");
                }
                if (!String.Equals(actual.Type, expectedColumn.Value, StringComparison.Ordinal)) {
                    throw new InvalidOperationException("GriefLedger database schema validation failed: " + table.Key + "." + expectedColumn.Key + " must use PostgreSQL type " + expectedColumn.Value + ".");
                }
                if (expectedColumn.Key == "id" && !actual.IsIdentity) {
                    throw new InvalidOperationException("GriefLedger database schema validation failed: " + table.Key + ".id must be an identity column.");
                }
                if (table.Key == "blockmutationlogs" && actual.IsNullable != BlockMutationColumnNullability[expectedColumn.Key]) {
                    throw new InvalidOperationException("GriefLedger database schema validation failed: blockmutationlogs." + expectedColumn.Key + " has incompatible nullability.");
                }
            }
        }

        foreach (string tableName in RequiredColumnTypes.Keys) {
            cmd.Parameters.Clear();
            cmd.CommandText = @"SELECT EXISTS (
                SELECT 1
                FROM pg_catalog.pg_constraint constraint_row
                JOIN pg_catalog.pg_class table_row ON table_row.oid = constraint_row.conrelid
                JOIN pg_catalog.pg_namespace schema_row ON schema_row.oid = table_row.relnamespace
                JOIN pg_catalog.pg_attribute id_column
                  ON id_column.attrelid = table_row.oid
                 AND id_column.attname = 'id'
                 AND NOT id_column.attisdropped
                WHERE schema_row.nspname = current_schema()
                  AND table_row.relname = @table_name
                  AND constraint_row.contype = 'p'
                  AND NOT constraint_row.condeferrable
                  AND NOT constraint_row.condeferred
                  AND constraint_row.convalidated
                  AND constraint_row.conkey = ARRAY[id_column.attnum]::smallint[]
            );";
            AddParameter(cmd, "@table_name", NpgsqlDbType.Text, tableName);
            if (!(bool)(cmd.ExecuteScalar() ?? false)) {
                throw new InvalidOperationException("GriefLedger database schema validation failed: " + tableName + ".id must be the sole column of a validated, non-deferrable primary key.");
            }
        }

        cmd.Parameters.Clear();
        cmd.CommandText = @"SELECT EXISTS (
            SELECT 1
            FROM pg_catalog.pg_index index_row
            JOIN pg_catalog.pg_class table_row ON table_row.oid = index_row.indrelid
            JOIN pg_catalog.pg_namespace schema_row ON schema_row.oid = table_row.relnamespace
            JOIN pg_catalog.pg_attribute uid_column
              ON uid_column.attrelid = table_row.oid
             AND uid_column.attname = 'playeruid'
             AND NOT uid_column.attisdropped
            WHERE schema_row.nspname = current_schema()
              AND table_row.relname = 'players'
              AND index_row.indisunique
              AND index_row.indimmediate
              AND index_row.indisvalid
              AND index_row.indisready
              AND index_row.indpred IS NULL
              AND index_row.indexprs IS NULL
              AND index_row.indnkeyatts = 1
              AND index_row.indkey[0] = uid_column.attnum
        );";
        if (!(bool)(cmd.ExecuteScalar() ?? false)) {
            throw new InvalidOperationException("GriefLedger database schema validation failed: players.playeruid must have a valid, immediate, non-partial single-column unique index usable by ON CONFLICT.");
        }

        ValidateBlockMutationForeignKeys(connection, transaction);
        ValidateBlockMutationChecks(connection, transaction);
    }

    private static void ValidateBlockMutationForeignKeys(NpgsqlConnection connection, NpgsqlTransaction transaction) {
        var expected = new Dictionary<string, (string Column, string ReferencedTable)>(StringComparer.Ordinal) {
            ["fk_blockmutationlogs_player"] = ("player_id", "players"),
            ["fk_blockmutationlogs_operator"] = ("operator_player_id", "players"),
            ["fk_blockmutationlogs_source"] = ("source_mutation_id", "blockmutationlogs")
        };
        using var cmd = connection.CreateCommand();
        cmd.Transaction = transaction;
        cmd.CommandText = @"SELECT constraint_row.conname,
                local_column.attname, referenced_schema.nspname = current_schema(), referenced_table.relname, referenced_column.attname,
                constraint_row.confupdtype::text, constraint_row.confdeltype::text,
                constraint_row.confmatchtype::text, constraint_row.convalidated,
                constraint_row.condeferrable, constraint_row.condeferred,
                cardinality(constraint_row.conkey), cardinality(constraint_row.confkey)
            FROM pg_catalog.pg_constraint constraint_row
            JOIN pg_catalog.pg_class local_table ON local_table.oid = constraint_row.conrelid
            JOIN pg_catalog.pg_namespace schema_row ON schema_row.oid = local_table.relnamespace
            JOIN pg_catalog.pg_class referenced_table ON referenced_table.oid = constraint_row.confrelid
            JOIN pg_catalog.pg_namespace referenced_schema ON referenced_schema.oid = referenced_table.relnamespace
            JOIN pg_catalog.pg_attribute local_column
              ON local_column.attrelid = local_table.oid AND local_column.attnum = constraint_row.conkey[1]
            JOIN pg_catalog.pg_attribute referenced_column
              ON referenced_column.attrelid = referenced_table.oid AND referenced_column.attnum = constraint_row.confkey[1]
