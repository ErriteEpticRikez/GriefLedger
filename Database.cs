    private static void ValidateBlockMutationIndex(NpgsqlConnection connection, NpgsqlTransaction transaction,
        string indexName, string[] expectedKeys, short[] expectedOptions, bool expectedUnique, string? expectedPredicate,
        bool expectedNullsNotDistinct = false) {
        using var cmd = connection.CreateCommand();
        cmd.Transaction = transaction;
        cmd.CommandText = @"SELECT index_row.indisunique, index_row.indisvalid, index_row.indisready,
                index_row.indimmediate, index_row.indnullsnotdistinct, index_row.indnkeyatts, index_row.indnatts,
                index_row.indexprs IS NULL, access_method.amname,
                pg_catalog.pg_get_expr(index_row.indpred, index_row.indrelid, false),
                ARRAY(SELECT pg_catalog.pg_get_indexdef(index_row.indexrelid, key_number, false)
                      FROM generate_series(1, index_row.indnkeyatts) key_number ORDER BY key_number),
                index_row.indoption::smallint[]
            FROM pg_catalog.pg_index index_row
            JOIN pg_catalog.pg_class index_table ON index_table.oid = index_row.indexrelid
            JOIN pg_catalog.pg_class data_table ON data_table.oid = index_row.indrelid
            JOIN pg_catalog.pg_namespace schema_row ON schema_row.oid = data_table.relnamespace
            JOIN pg_catalog.pg_am access_method ON access_method.oid = index_table.relam
            WHERE schema_row.nspname = current_schema()
              AND data_table.relname = 'blockmutationlogs'
              AND index_table.relname = @index_name;";
        AddParameter(cmd, "@index_name", NpgsqlDbType.Text, indexName);
        using var reader = cmd.ExecuteReader();
        if (!reader.Read()) throw new InvalidOperationException("GriefLedger database schema validation failed: required index " + indexName + " was not found.");
        string? actualPredicate = reader.IsDBNull(9) ? null : reader.GetString(9);
        string[] actualKeys = reader.GetFieldValue<string[]>(10);
        short[] actualOptions = reader.GetFieldValue<short[]>(11);
        if (reader.GetBoolean(0) != expectedUnique || !reader.GetBoolean(1) || !reader.GetBoolean(2)
            || !reader.GetBoolean(3) || reader.GetBoolean(4) != expectedNullsNotDistinct
            || reader.GetInt16(5) != expectedKeys.Length || reader.GetInt16(6) != expectedKeys.Length
            || !reader.GetBoolean(7) || reader.GetString(8) != "btree"
            || !actualKeys.AsSpan().SequenceEqual(expectedKeys)
            || !actualOptions.AsSpan().SequenceEqual(expectedOptions)
            || (actualPredicate == null) != (expectedPredicate == null)
            || (actualPredicate != null && NormalizeSql(actualPredicate) != NormalizeSql(expectedPredicate!))) {
            throw new InvalidOperationException("GriefLedger database schema validation failed: index " + indexName + " has an incompatible definition.");
        }
        if (reader.Read()) throw new InvalidOperationException("GriefLedger database schema validation failed: index " + indexName + " is ambiguous.");
    }

    private static string NormalizeSql(string value) {
        var builder = new System.Text.StringBuilder(value.Length);
        int index = 0;
        while (index < value.Length) {
            char character = value[index];
            if (character is '\'' or '"') {
                char quote = character;
                builder.Append(character);
                index++;
                while (index < value.Length) {
                    character = value[index];
                    builder.Append(character);
                    index++;
                    if (character != quote) continue;
                    if (index < value.Length && value[index] == quote) {
                        builder.Append(value[index]);
                        index++;
                        continue;
                    }
                    break;
                }
                continue;
            }
            if (character == '$' && TryReadDollarQuoteDelimiter(value, index, out string delimiter)) {
                builder.Append(delimiter);
                index += delimiter.Length;
                int closing = value.IndexOf(delimiter, index, StringComparison.Ordinal);
                if (closing < 0) {
                    builder.Append(value, index, value.Length - index);
                    break;
                }
                builder.Append(value, index, closing - index + delimiter.Length);
                index = closing + delimiter.Length;
                continue;
            }
            if (!char.IsWhiteSpace(character)) builder.Append(character);
            index++;
        }
        return builder.ToString();
    }

    private static bool TryReadDollarQuoteDelimiter(string value, int offset, out string delimiter) {
        int index = offset + 1;
        if (index < value.Length && value[index] == '$') {
            delimiter = "$$";
            return true;
        }
        if (index >= value.Length || !(value[index] == '_' || char.IsAsciiLetter(value[index]))) {
            delimiter = string.Empty;
            return false;
        }
        index++;
        while (index < value.Length && (value[index] == '_' || char.IsAsciiLetterOrDigit(value[index]))) index++;
        if (index >= value.Length || value[index] != '$') {
            delimiter = string.Empty;
            return false;
        }
        delimiter = value.Substring(offset, index - offset + 1);
        return true;
    }

    private void WorkerLoop() {
        foreach (WriterWorkItem task in databaseTasks.GetConsumingEnumerable()) {
            Interlocked.Increment(ref activeWriterWorkCount);
            try {
                Exception? writerFailure = Volatile.Read(ref terminalWriterFailure);
                if (writerFailure != null) {
                    task.Fail?.Invoke(new DatabaseWriterUnavailableException(writerFailure));
                    continue;
                }
                try {
                    using (var connection = dataSource.OpenConnection()) {
                        task.Execute(connection);
                    }
                    task.Complete?.Invoke();
                }
                catch (Exception ex) {
                    Interlocked.CompareExchange(ref terminalWriterFailure, ex, null);
                    task.Fail?.Invoke(ex);
                    // Awaited writes have an observer/caller which owns the single contextual error
                    // report. Only fire-and-forget writes need the worker to report the first failure.
                    if (task.Fail == null) {
                        LogError("GriefLedger: A queued database write failed and was not retried: " + ex);
                    }
                }
            }
            finally {
                Interlocked.Decrement(ref activeWriterWorkCount);
            }
        }
    }

    private static void LogError(string message) {
        Main.API?.Logger.Error(message);
    }

    private void QueueWrite(Action<NpgsqlConnection> task) {
        bool rejected = false;
        lock (lifecycleLock) {
            if (!acceptingWrites) {
                LogError("GriefLedger: Rejected a database write because the database is shutting down.");
                return;
            }
            if (Volatile.Read(ref terminalWriterFailure) != null) {
                Interlocked.Increment(ref rejectedWriterWorkCount);
                return;
            }
            if (!databaseTasks.TryAdd(new WriterWorkItem { Execute = task })) rejected = true;
        }
        if (rejected) ReportWriterQueueFull();
    }

    private Task<long> QueueResultWrite(Action<NpgsqlConnection, Action<long>> execute, bool isBarrier) {
        var completion = new TaskCompletionSource<long>(TaskCreationOptions.RunContinuationsAsynchronously);
        long result = 0;
        bool queueFull = false;
        lock (lifecycleLock) {
            if (!acceptingWrites) {
                completion.SetException(new ObjectDisposedException(nameof(Database), "The database writer is shutting down."));
                return completion.Task;
            }
            Exception? writerFailure = Volatile.Read(ref terminalWriterFailure);
            if (writerFailure != null) {
                Interlocked.Increment(ref rejectedWriterWorkCount);
                completion.SetException(new DatabaseWriterUnavailableException(writerFailure));
                return completion.Task;
            }
            if (!databaseTasks.TryAdd(new WriterWorkItem {
                Execute = connection => execute(connection, value => result = value),
                Complete = () => completion.TrySetResult(result),
                Fail = exception => completion.TrySetException(exception),
                IsBarrier = isBarrier
            })) {
                queueFull = true;
                completion.TrySetException(new DatabaseWriterQueueFullException(databaseTasks.BoundedCapacity));
            }
        }
        if (queueFull) ReportWriterQueueFull();
        return completion.Task;
    }

    internal int PendingWriterWorkCount => databaseTasks.Count;
    internal int ActiveWriterWorkCount => Volatile.Read(ref activeWriterWorkCount);
    internal long RejectedWriterWorkCount => Interlocked.Read(ref rejectedWriterWorkCount);

    private void ReportWriterQueueFull() {
        Interlocked.Increment(ref rejectedWriterWorkCount);
        long now = Environment.TickCount64;
        long prior = Interlocked.Read(ref lastQueueFullLogTicks);
        if (now - prior >= 10_000 && Interlocked.CompareExchange(ref lastQueueFullLogTicks, now, prior) == prior) {
            LogError("GriefLedger: Database writer queue is full; work was rejected to protect the game thread and bound retained memory.");
        }
    }

    private bool TryBeginRead(string operation) {
        lock (lifecycleLock) {
            if (!acceptingReads) {
                LogError("GriefLedger: Rejected database read '" + operation + "' because the database is shutting down.");
                return false;
            }
            activeReads++;
            readsDrained.Reset();
            return true;
        }
    }

    private void EndRead() {
        lock (lifecycleLock) {
            activeReads--;
            if (activeReads == 0) readsDrained.Set();
        }
    }

    private void QueueRead(string operation, Action read) {
        if (!TryBeginRead(operation)) return;

        try {
            Task.Run(() => {
                try {
                    read();
                }
                catch (Exception ex) {
                    LogError("GriefLedger: Database read '" + operation + "' failed: " + ex);
                }
                finally {
                    EndRead();
                }
            });
        }
        catch (Exception ex) {
            EndRead();
            LogError("GriefLedger: Database read '" + operation + "' could not be scheduled: " + ex);
        }
    }

    private Task<T> QueueReadAsync<T>(string operation, System.Func<NpgsqlConnection, CancellationToken, Task<T>> read,
        CancellationToken cancellationToken) {
        ArgumentNullException.ThrowIfNull(read);
        if (!TryBeginRead(operation)) {
            return Task.FromException<T>(new ObjectDisposedException(nameof(Database), "The database is shutting down."));
        }

        try {
            return Task.Run(async () => {
                try {
                    cancellationToken.ThrowIfCancellationRequested();
                    await using NpgsqlConnection connection = await dataSource.OpenConnectionAsync(cancellationToken).ConfigureAwait(false);
                    return await read(connection, cancellationToken).ConfigureAwait(false);
                }
                finally {
                    EndRead();
                }
            }, CancellationToken.None);
        }
        catch (Exception exception) {
            EndRead();
            return Task.FromException<T>(exception);
        }
    }

